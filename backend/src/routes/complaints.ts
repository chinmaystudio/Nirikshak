import crypto from 'crypto';
import { Router, Request, Response } from 'express';
import { supabaseAdmin } from '../services/supabase.js';
import { isSafeStoragePath } from '../validation/paths.js';
import { CreateComplaintSchema } from '../validation/schemas.js';
import { rateLimit, requireHuman } from '../middleware/security.js';
import { GOVERNMENT_ROLES } from '../middleware/auth.js';

export const complaintsRouter = Router();

// Sanitizer for plain text inputs to prevent XSS (Rules 45, 87)
function sanitizeText(str: string): string {
  return str
    .replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, '')
    .replace(/<[^>]+>/g, '')
    .trim();
}

// POST /api/complaints - Submit grievance
complaintsRouter.post(
  '/',
  rateLimit({ windowMs: 60 * 1000, max: 20 }),
  requireHuman(),
  async (req: Request, res: Response) => {
    // DF-21: safeParse + first-issue message (same pattern as auth.ts/tenders.ts)
    const parsed = CreateComplaintSchema.safeParse(req.body);
    if (!parsed.success) {
      return res.status(400).json({
        success: false,
        error: { code: 'VALIDATION_ERROR', message: parsed.error.issues[0]?.message || 'Please check the complaint details.' },
      });
    }

    try {
      const { evidence_paths: rawEvidencePaths, ...compData } = parsed.data;
      // Clients from before the storage upload change send bare file names
      // (no stored file). Those are not evidence: they are dropped, the
      // complaint is still filed, and the response says so.
      const legacyNames = (rawEvidencePaths || []).filter((p) => !p.includes('/'));
      const evidence_paths = (rawEvidencePaths || []).filter((p) => p.includes('/'));

      // Extract optional authenticated user
      let userId: string | null = null;
      const authHeader = req.header('authorization');
      if (authHeader?.startsWith('Bearer ')) {
        const token = authHeader.slice(7).trim();
        try {
          const { data: authData } = await supabaseAdmin.auth.getUser(token);
          if (authData?.user) userId = authData.user.id;
        } catch {
          /* anonymous submission permitted */
        }
      }

      // Evidence files are uploaded by the signed-in complainant to the
      // complaint-evidence bucket under "<their user id>/..." (storage RLS,
      // migration 045). Anonymous complaints cannot attach files.
      if (evidence_paths && evidence_paths.length > 0) {
        if (!userId) {
          return res.status(401).json({
            success: false,
            error: { code: 'SIGN_IN_REQUIRED', message: 'Please sign in to attach photos or videos to a complaint.' },
          });
        }
        if (evidence_paths.some((p) => !isSafeStoragePath(p, userId))) {
          return res.status(400).json({
            success: false,
            error: { code: 'INVALID_PATH', message: 'Invalid evidence storage path format' },
          });
        }
      }

      const sanitizedTitle = sanitizeText(compData.title);
      const sanitizedDesc = sanitizeText(compData.description);

      const row = {
        ...compData,
        title: sanitizedTitle,
        description: sanitizedDesc,
        // DF-22: the author comes solely from the verified Bearer token
        // (null for anonymous submissions) — never from the request body.
        user_id: userId,
        // reference_number: generated by the database (migration 040)
        status: 'SUBMITTED',
      };
      let { data, error } = await supabaseAdmin.from('complaints').insert(row).select().single();
      if (error && error.code === '23502' && /reference_number/.test(error.message || '')) {
        // Database without migration 040 (no default): generate an
        // unguessable reference here instead.
        const reference_number = `NIR-CMP-${new Date().getFullYear()}-${crypto.randomInt(100000, 1000000)}-${crypto.randomBytes(3).toString('hex').toUpperCase()}`;
        ({ data, error } = await supabaseAdmin.from('complaints').insert({ ...row, reference_number }).select().single());
      }

      if (error) {
        // DF-21: database failures are 500s with a generic message, not 400s
        console.error('Complaint creation failed', { code: error.code, message: error.message });
        return res.status(500).json({
          success: false,
          error: { code: 'COMPLAINT_CREATE_FAILED', message: 'The complaint could not be submitted.' },
        });
      }

      if (evidence_paths && evidence_paths.length > 0) {
        const evs = evidence_paths.map((p) => ({
          complaint_id: data.id,
          storage_path: p,
        }));
        const { error: evidenceError } = await supabaseAdmin.from('complaint_evidence').insert(evs);
        if (evidenceError) {
          console.error('Complaint evidence insert failed', { code: evidenceError.code, message: evidenceError.message });
        }
      }

      // Record audit log
      await supabaseAdmin.from('audit_logs').insert({
        actor_id: userId,
        action: 'COMPLAINT_FILED',
        entity_type: 'complaints',
        entity_id: data.id,
        new_value: {
          reference_number: data.reference_number,
          project_id: data.project_id,
          category: data.category,
        },
      });

      res.status(201).json({
        success: true,
        data,
        ...(legacyNames.length > 0
          ? { warning: 'Attached files were not uploaded. Reload the page and attach them again from the complaint page.' }
          : {}),
      });
    } catch (err: any) {
      console.error('Unexpected complaint creation error', err);
      res.status(500).json({ success: false, error: { code: 'COMPLAINT_ERROR', message: 'The complaint could not be submitted.' } });
    }
  }
);

// GET /api/complaints/track/:ref - Track complaint status with PII redaction (Rules 74, 75)
complaintsRouter.get('/track/:ref', rateLimit({ windowMs: 60 * 1000, max: 30 }), async (req: Request, res: Response) => {
  try {
    const { ref } = req.params;

    // Check caller's identity
    const authHeader = req.header('authorization');
    let callerId: string | null = null;
    let isGovernment = false;

    if (authHeader?.startsWith('Bearer ')) {
      const token = authHeader.slice(7).trim();
      try {
        const { data: authData } = await supabaseAdmin.auth.getUser(token);
        if (authData?.user) {
          callerId = authData.user.id;
          const { data: member } = await supabaseAdmin
            .from('organization_members')
            .select('role')
            .eq('user_id', callerId)
            .ilike('status', 'active')
            .limit(1)
            .maybeSingle();

          if (member && GOVERNMENT_ROLES.includes(member.role)) {
            isGovernment = true;
          }
        }
      } catch {
        /* unauthenticated track request */
      }
    }

    const { data, error } = await supabaseAdmin
      .from('complaints')
      .select('*, complaint_updates(*), complaint_evidence(*), projects(project_name, project_authority)')
      .eq('reference_number', ref)
      .single();

    if (error || !data) {
      return res.status(404).json({ success: false, error: { code: 'NOT_FOUND', message: 'Complaint reference not found' } });
    }

    // Check if caller is authorized owner or government official
    const isOwner = callerId !== null && data.user_id === callerId;

    if (!isOwner && !isGovernment) {
      // Privacy Protection (Rule 74): Redact citizen PII and internal investigator updates
      const redacted = {
        id: data.id,
        reference_number: data.reference_number,
        project_id: data.project_id,
        category: data.category,
        title: data.title,
        status: data.status,
        created_at: data.created_at,
        updated_at: data.updated_at,
        projects: data.projects,
        // Public tracking shows the status history only. Notes can contain
        // investigator remarks or the complainant's personal details, so they
        // are visible only to the complainant and officers.
        complaint_updates: (data.complaint_updates || []).map((u: any) => ({
          id: u.id,
          previous_status: u.previous_status,
          new_status: u.new_status,
          created_at: u.created_at,
        })),
      };
      return res.json({ success: true, data: redacted });
    }

    res.json({ success: true, data });
  } catch (err: any) {
    console.error('Complaint tracking failed', { message: err?.message });
    res.status(500).json({ success: false, error: { code: 'TRACK_ERROR', message: 'Error retrieving complaint status' } });
  }
});
